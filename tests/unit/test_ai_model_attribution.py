import re

import pandas as pd

import app as app_module
from app import AI_SUMMARY_CACHE, DATAFRAME_CACHE, app
from data_analysis.ai import engine as ai_engine
from data_analysis.ai import service as ai_service


class _Resp:
    def __init__(self, text: str):
        self.text = text


def test_summary_simple_fallback_keeps_model_marker(monkeypatch):
    responses = iter([_Resp(""), _Resp("<p>Fallback summary</p>")])

    monkeypatch.setattr(ai_engine, "ensure_ai_ready", lambda **_kwargs: True)
    monkeypatch.setattr(ai_engine, "_call_gemini", lambda *_args, **_kwargs: next(responses))
    monkeypatch.setattr(ai_engine, "_extract_text_from_gemini_response", lambda resp, **_kwargs: resp.text)
    monkeypatch.setattr(ai_engine, "_diagnose_gemini_response", lambda *_args, **_kwargs: "")
    monkeypatch.setattr(ai_engine, "_get_finish_reason", lambda *_args, **_kwargs: None)
    monkeypatch.setattr(ai_engine, "CURRENT_MODEL_NAME", "models/gemini-3.0-flash")

    out = ai_service.get_ai_summary_with_file(
        pd.DataFrame({"x": [1, 2]}),
        extra_context="ctx",
        sanitize_ai_html_fn=lambda s: s,
    )

    assert "Fallback summary" in out
    assert "<!-- model:models/gemini-3.0-flash -->" in out


