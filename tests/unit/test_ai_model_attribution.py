def test_overview_post_keeps_distinct_summary_and_answer_models(monkeypatch):
    filename = "a" * 40 + ".csv"
    DATAFRAME_CACHE.set(filename, pd.DataFrame({"value": [1.0, 2.0, 3.0]}))
    AI_SUMMARY_CACHE[filename] = "<p>Summary</p><!-- model:models/gemini-3.0-flash -->"

    monkeypatch.setattr(
        app_module,
        "get_ai_answer_with_file",
        lambda *_args, **_kwargs: "<p>Answer</p><!-- model:models/gemini-2.5-flash-lite -->",
    )

    with app.test_client() as client:
        response = client.post(
            f"/analyze/{filename}?view=overview",
            data={"question": "Explain this"},
        )

    text = response.data.decode("utf-8", errors="replace")
    assert response.status_code == 200
    assert "Generated by gemini-3.0-flash" in text
    assert "Generated by gemini-2.5-flash-lite" in text


def test_overview_post_hides_summary_attribution_on_quota_error(monkeypatch):
    filename = "b" * 40 + ".csv"
    DATAFRAME_CACHE.set(filename, pd.DataFrame({"value": [1.0, 2.0, 3.0]}))
    AI_SUMMARY_CACHE[filename] = "<p>AI summary unavailable: 429 You exceeded your current quota.</p>"

    monkeypatch.setattr(
        app_module,
        "get_ai_answer_with_file",
        lambda *_args, **_kwargs: "<p>Answer</p><!-- model:models/gemini-2.5-flash-lite -->",
    )

    with app.test_client() as client:
        response = client.post(
            f"/analyze/{filename}?view=overview",
            data={"question": "Explain this"},
        )

    text = response.data.decode("utf-8", errors="replace")
    assert response.status_code == 200
    assert "AI summary unavailable: 429" in text
    assert re.search(r'id="ai-summary-attribution"\s+hidden', text) is not None
    assert "Generated by gemini-2.5-flash-lite" in text


